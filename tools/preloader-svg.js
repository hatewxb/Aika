// Generates the SVG masks of the sign-in window presets (options/preloader-*.css):
// sections/login-rain.css (Terminal) and sections/login-orbits.css (Orbits).
// Each file sets two :root variables — the animated mask (SMIL: CEF animates SVG
// images, masks included; checked 2026-10-27) and a still one for
// Performance: Low. The mask is white on transparent: the color comes from
// the layer's background, so the presets follow the user's color preset.
//   node tools/preloader-svg.js
const fs = require("fs");
const path = require("path");
const W = 700, H = 440;
let seed = 7;
const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647; // stable output between runs
const pick = s => s[Math.floor(rnd() * s.length)];
const uri = svg => `url("data:image/svg+xml,${encodeURIComponent(svg.replace(/\s+/g, " ")).replace(/%20/g, " ")}")`;
const header = what => `/* GENERATED by tools/preloader-svg.js — do not edit by hand.\n   ${what} */\n\n`;

// --- Terminal: columns of hex glyphs falling, a fading tail, the head brightest
function rain(live) {
  const PITCH = 20, ROW = 16, GLYPHS = "0123456789ABCDEF/:#=+*"; // no < > & — they break the SVG markup
  let cols = "";
  for (let x = PITCH / 2; x < W; x += PITCH) {
    const n = 8 + Math.floor(rnd() * 16), len = n * ROW;
    const tspans = Array.from({ length: n }, (_, i) => `<tspan x="${x}" dy="${i ? ROW : 0}">${pick(GLYPHS)}</tspan>`).join("");
    const dur = (3 + rnd() * 5).toFixed(2);
    const move = live
      ? `<animateTransform attributeName="transform" type="translate" values="0 ${-len};0 ${H}" dur="${dur}s" begin="-${(rnd() * dur).toFixed(2)}s" repeatCount="indefinite"/>`
      : "";
    const still = live ? "" : ` transform="translate(0 ${Math.round(rnd() * (H + len) - len)})"`;
    cols += `<g${still}>${move}<text y="${ROW}" fill="url(#t)" fill-opacity="${(0.45 + rnd() * 0.55).toFixed(2)}">${tspans}</text></g>`;
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" font-family="Consolas, monospace" font-size="14" text-anchor="middle">
    <defs><linearGradient id="t" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#fff" stop-opacity="0"/><stop offset=".8" stop-color="#fff" stop-opacity=".55"/><stop offset="1" stop-color="#fff"/></linearGradient></defs>${cols}</svg>`;
}

// --- Orbits: three tilted ellipses round the mark (349, 175), 0 and 1 riding them
function orbits(live) {
  const CX = 349, CY = 175;
  const rings = [[280, 74, 14, 14, 5], [222, 58, -22, 10, 4], [330, 104, 5, 20, 6]];
  let out = "";
  for (const [a, b, rot, dur, n] of rings) {
    const p = `M ${CX - a} ${CY} A ${a} ${b} 0 1 1 ${CX + a} ${CY} A ${a} ${b} 0 1 1 ${CX - a} ${CY}`;
    let bits = "";
    for (let k = 0; k < n; k++) {
      const op = (1 - k * 0.13).toFixed(2), bit = rnd() > 0.5 ? "1" : "0";
      if (live) {
        bits += `<g><animateMotion path="${p}" dur="${dur}s" begin="-${(dur * k / n).toFixed(2)}s" repeatCount="indefinite"/><text transform="rotate(${-rot})" fill-opacity="${op}">${bit}</text></g>`;
      } else {
        const t = (k / n) * Math.PI * 2 + rnd();
        bits += `<text transform="translate(${(CX - a * Math.cos(t)).toFixed(1)} ${(CY - b * Math.sin(t)).toFixed(1)}) rotate(${-rot})" fill-opacity="${op}">${bit}</text>`;
      }
    }
    out += `<g transform="rotate(${rot} ${CX} ${CY})"><path d="${p}" fill="none" stroke="#fff" stroke-opacity=".12"/>${bits}</g>`;
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" font-family="Consolas, monospace" font-size="12" font-weight="bold" fill="#fff" text-anchor="middle" dominant-baseline="central">${out}</svg>`;
}

const dir = path.join(__dirname, "..", "sections");
fs.writeFileSync(path.join(dir, "login-rain.css"), header("The Terminal preset's glyph rain (sign-in window, 700×440).") +
  `:root {\n    --aika-pl-rain-live: ${uri(rain(true))};\n    --aika-pl-rain-still: ${uri(rain(false))};\n}\n`);
fs.writeFileSync(path.join(dir, "login-orbits.css"), header("The Orbits preset's ellipses and riding bits (sign-in window, 700×440).") +
  `:root {\n    --aika-pl-orbits-live: ${uri(orbits(true))};\n    --aika-pl-orbits-still: ${uri(orbits(false))};\n}\n`);
console.log("ok");
